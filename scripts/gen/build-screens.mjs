#!/usr/bin/env node
// Compiles figma/rest/*.json into screens/gen/screens.js + screens.css (IMPL-PLAN.md §1).
// Plain Node, no dependencies:  node scripts/gen/build-screens.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFile, twinMap, isSvgRoot, solidPaints } from './lib/figma.mjs';
import { Translator } from './lib/node.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(readFileSync(`${ROOT}/scripts/gen/screens.json`, 'utf8'));
const overridesList = JSON.parse(readFileSync(`${ROOT}/scripts/gen/overrides.json`, 'utf8')).overrides || [];
const overrides = new Map();
for (const o of overridesList) {
  if (!o.node || !(o.css || o.asset) || !o.reason) throw new Error(`override needs node, css (or asset) and reason: ${JSON.stringify(o)}`);
  overrides.set(o.node, o);
}

const SCROLL_NAME = { send: 'Screen content', receive: 'Scroll content', collect: 'Content' };
const files = new Map();
const file = key => files.get(key) || files.set(key, loadFile(ROOT, key)).get(key);

// ---- deduplicated classes ----
const classes = new Map(); // decl -> name
const names = new Map();   // name -> decl
function hash(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return (h >>> 0).toString(36);
}
function classFor(decl) {
  if (classes.has(decl)) return classes.get(decl);
  let name = `g-${hash(decl)}`, k = 0;
  while (names.has(name)) name = `g-${hash(decl + '#' + ++k)}`;
  classes.set(decl, name); names.set(name, decl);
  return name;
}

/** The tap target for a TEXT trigger: nearest ancestor frame that looks like a button (fill + radius), else the text's parent. */
function hotspotFor(f, triggerId, frameId, scrollId) {
  const t = f.byId.get(triggerId);
  if (!t) throw new Error(`trigger ${triggerId} not found`);
  let n = f.parent.get(t.id);
  const first = n;
  while (n && n.id !== frameId && n.id !== scrollId) {
    if (solidPaints(n.fills).length && (n.cornerRadius || n.rectangleCornerRadii)) return n.id;
    const p = f.parent.get(n.id);
    if (!p || p.id === frameId) break;
    n = p;
  }
  return first.id;
}

const out = [];
const counts = {};
for (const sc of manifest.screens) {
  const [zone, nStr] = sc.key.split('-');
  const f = file(manifest.files[zone]);
  const app = f.byId.get(sc.node);
  if (!app) throw new Error(`frame ${sc.node} not found`);
  const twin = sc.twin ? f.byId.get(sc.twin) : null;
  const struct = twin || app;
  const map = twin ? twinMap(app, twin) : null;
  const scrollNode = app.children.find(c => c.name === SCROLL_NAME[zone]);
  if (!scrollNode) throw new Error(`${sc.key}: no "${SCROLL_NAME[zone]}" child`);
  const tr = new Translator({
    root: ROOT, fileKey: f.fileKey, zone, screenKey: sc.key, overrides, classFor,
    scrollId: scrollNode.id, frameId: app.id,
    idOf: n => (map ? { node: map.get(n.id), twin: n.id } : { node: n.id }),
  });
  const html = tr.render(struct, null, 0);
  const hot = /^\d+:\d+$/.test(sc.go) ? hotspotFor(f, sc.go, app.id, scrollNode.id) : null;
  if (sc.back && !f.byId.get(sc.back)) throw new Error(`${sc.key}: back ${sc.back} not found`);
  const h = struct.absoluteBoundingBox.height;
  if (Math.abs(h - sc.h) > 0.5) throw new Error(`${sc.key}: height ${h} != manifest ${sc.h}`);
  counts[sc.key] = tr.used.size;
  out.push({
    key: sc.key, zone, n: +nStr, node: app.id, twin: twin ? twin.id : null, title: sc.title, h,
    go: sc.go, hot, back: sc.back || null, auto: sc.auto || null, scan: sc.scan || null,
    scroll: scrollNode.id, html,
  });
}

const BASE = `/* generated by scripts/gen/build-screens.mjs from figma/rest/*.json; do not edit */
.fr,.fr *{box-sizing:border-box;margin:0;padding:0;border:0;min-width:0}
.fr{font-family:Inter,sans-serif;font-optical-sizing:none;font-kerning:normal;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale;text-rendering:geometricPrecision;position:relative;overflow:hidden;color:#000}
.fr span{display:block}
.fr span span{display:inline}
.fr svg{display:block;overflow:visible}
`;
const css = BASE + [...classes].map(([decl, name]) => `.${name}{${decl}}`).join('\n') + '\n';
const js = `/* generated by scripts/gen/build-screens.mjs from figma/rest/*.json; do not edit */\nwindow.FIGMA_SCREENS = ${JSON.stringify(out)};\n`;
mkdirSync(`${ROOT}/screens/gen`, { recursive: true });
writeFileSync(`${ROOT}/screens/gen/screens.css`, css);
writeFileSync(`${ROOT}/screens/gen/screens.js`, js);
console.log(`screens: ${out.length}, elements: ${Object.values(counts).reduce((a, b) => a + b, 0)}, classes: ${classes.size}, js ${(js.length / 1024).toFixed(0)} KB, css ${(css.length / 1024).toFixed(0)} KB, overrides: ${overrides.size}`);
